import { describe, expect, it } from "vitest";
import { ComputeReport, LeanReport } from "@/lib/schema";
import { json } from "./helpers";

describe("verification reports (generated by npm run verify:lean / verify:compute)", () => {
  const lean = LeanReport.parse(json("content/verification/lean-report.json"));
  const compute = ComputeReport.parse(json("content/verification/compute-report.json"));

  it("records a successful Lean build with no sorry in the library", () => {
    expect(lean.build.success).toBe(true);
    expect(lean.declarations.filter((d) => d.usesSorry)).toEqual([]);
    // Mathlib is pinned to the release tag that matches the Lean toolchain.
    expect(lean.mathlib).toMatch(/^v4\.35\.0 \([0-9a-f]{12}\)$/);
  });
  it("keeps the elementary modules (Kindergarten to Grade 8) on core Lean", () => {
    const lessons = new Map<string, string>();
    for (const d of lean.declarations) lessons.set(d.file, d.foundation);
    const core = ["Collections", "Sets", "Integers", "Functions", "Counting", "Fractions", "ModularArithmetic", "PythagoreanTheorem"];
    for (const m of core) expect(lessons.get(`formal/Lumenary/${m}.lean`), m).toBe("core");
  });
  it("records that every Lean exercise elaborates and has a compiled solution", () => {
    const names = new Set(lean.declarations.map((d) => d.name));
    for (const ex of lean.exercises) {
      expect(ex.elaborates, ex.name).toBe(true);
      expect(ex.sorryCount, ex.name).toBeGreaterThan(0);
      expect(ex.solution && names.has(ex.solution), ex.name).toBe(true);
    }
  });
  it("records passing computational experiments", () => {
    expect(compute.pytest.failed).toBe(0);
    for (const e of compute.experiments) expect(e.ran && e.testsPassed, e.id).toBe(true);
  });
});
